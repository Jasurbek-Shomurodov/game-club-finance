-- One shared set of bar product categories for both Pixel Gaming clubs.
--
-- Categories were typed by hand per club and drifted into 24 values in two
-- languages ("Напиток" and "напиток", "ichimlik", "bar", "jb", "buyurtma bn"),
-- and 11 products had none, so the purchase history's category filter split
-- one kind of product across several entries. Every product of the two clubs,
-- archived ones included (their old purchases are still filtered), now gets
-- one of twelve Russian categories, matched by product name.
--
-- Archived product metadata is read-only (trg_protect_product_history). The
-- trigger is lifted for this one statement only: the category is a label, and
-- no stock, price or ledger value changes. Clubs other than these two, and any
-- database without them, are untouched.

create temporary table bar_category_map (name text primary key, category text not null) on commit drop;

